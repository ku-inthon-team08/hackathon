-- 감각 과부하 지도 기본 스키마
-- 기준 데이터(핫스팟·센서·쉼터·도로망) → 수집 데이터(혼잡도·센서 측정값) → 계산 결과(도로 구간 감각 부하)

create extension if not exists postgis with schema extensions;

-- ───────────── 기준 데이터 ─────────────

-- 실시간 도시데이터 장소 (예: POI001 강남역)
create table public.hotspots (
  area_cd  text primary key,
  area_nm  text not null,
  category text,                               -- 관광특구 / 발달상권 / 공원 / 인구밀집지역 / 고궁·문화유산
  center   geography(Point, 4326) not null,
  area     geography(MultiPolygon, 4326)       -- 장소 영역. 도로 구간의 인파 값을 정할 때 사용
);

-- S-DoT 센서
create table public.sensors (
  sensor_id text primary key,                  -- S-DoT 시리얼
  kind      text not null check (kind in ('env', 'flow')),  -- env: 소음·조도, flow: 유동인구
  geom      geography(Point, 4326) not null,
  gu        text,
  dong      text
);

-- 쉼터(갈 곳)
create table public.places (
  id        bigint generated by default as identity primary key,
  kind      text not null check (kind in ('library', 'park')),
  name      text not null,
  address   text,
  geom      geography(Point, 4326) not null,
  open_info jsonb,                             -- 예: {"open":"09:00","close":"22:00","closed":"매주 월요일"}
  source    text not null,                     -- 데이터 출처 (예: seoul_library)
  source_id text,
  unique (source, source_id)
);

-- 보행 도로망 (osmnx로 시연 지역만 추출해 적재)
create table public.road_nodes (
  id   bigint primary key,                     -- OSM node id
  geom geography(Point, 4326) not null
);

create table public.road_edges (
  id       bigint generated by default as identity primary key,
  source   bigint not null references public.road_nodes (id),
  target   bigint not null references public.road_nodes (id),
  length_m double precision not null,
  highway  text,                               -- OSM 도로 등급 (primary, residential, footway ...)
  geom     geography(LineString, 4326) not null
);

-- ───────────── 수집 데이터 ─────────────

-- 혼잡도 level: 1 여유 · 2 보통 · 3 약간 붐빔 · 4 붐빔
create table public.congestion_obs (
  area_cd     text not null references public.hotspots (area_cd),
  observed_at timestamptz not null,
  level       smallint not null check (level between 1 and 4),
  ppl_min     integer,
  ppl_max     integer,
  fetched_at  timestamptz not null default now(),
  primary key (area_cd, observed_at)
);

create table public.congestion_forecast (
  area_cd    text not null references public.hotspots (area_cd),
  fcst_at    timestamptz not null,
  level      smallint not null check (level between 1 and 4),
  ppl_min    integer,
  ppl_max    integer,
  fetched_at timestamptz not null default now(),
  primary key (area_cd, fcst_at)
);

create table public.sensor_obs (
  sensor_id   text not null references public.sensors (sensor_id),
  observed_at timestamptz not null,
  noise_db    real,
  lux         real,
  flow_count  integer,
  fetched_at  timestamptz not null default now(),
  primary key (sensor_id, observed_at)
);

-- 과거 CSV로 만든 요일·시간대별 평균. 실시간 값이 없을 때와 출발 전 계획에 사용
create table public.sensor_profile (
  sensor_id  text not null references public.sensors (sensor_id),
  day_type   text not null check (day_type in ('weekday', 'weekend')),
  hour       smallint not null check (hour between 0 and 23),
  noise_db   real,
  lux        real,
  flow_count real,
  primary key (sensor_id, day_type, hour)
);

-- ───────────── 계산 결과 ─────────────

-- 도로 구간별 감각 부하 (IDW 보간 결과를 0~1로 정규화). 수집할 때마다 다시 계산
create table public.edge_exposure (
  edge_id     bigint primary key references public.road_edges (id) on delete cascade,
  noise_db    real,
  lux         real,
  noise_n     real not null default 0 check (noise_n between 0 and 1),
  light_n     real not null default 0 check (light_n between 0 and 1),
  crowd_n     real not null default 0 check (crowd_n between 0 and 1),
  confidence  real not null default 0 check (confidence between 0 and 1),
  computed_at timestamptz not null default now()
);

-- ───────────── 운영 ─────────────

-- 수집 기록. error에 API 키가 섞일 수 있어 앱에는 공개하지 않고 data_status()로 요약만 보여준다
create table public.fetch_log (
  id         bigint generated by default as identity primary key,
  source     text not null,                    -- citydata / sdot_env / sdot_flow
  fetched_at timestamptz not null default now(),
  ok         boolean not null,
  row_count  integer,
  error      text
);

-- ───────────── 인덱스 ─────────────

create index hotspots_center_idx   on public.hotspots   using gist (center);
create index hotspots_area_idx     on public.hotspots   using gist (area);
create index sensors_geom_idx      on public.sensors    using gist (geom);
create index places_geom_idx       on public.places     using gist (geom);
create index road_nodes_geom_idx   on public.road_nodes using gist (geom);
create index road_edges_geom_idx   on public.road_edges using gist (geom);
create index road_edges_source_idx on public.road_edges (source);
create index road_edges_target_idx on public.road_edges (target);
create index fetch_log_source_idx  on public.fetch_log  (source, fetched_at desc);

-- ───────────── 권한 ─────────────
-- 앱(anon·authenticated)은 읽기만 한다. 쓰기는 service_role 키를 쓰는 수집기만 하고, service_role은 RLS를 우회한다

alter table public.hotspots            enable row level security;
alter table public.sensors             enable row level security;
alter table public.places              enable row level security;
alter table public.road_nodes          enable row level security;
alter table public.road_edges          enable row level security;
alter table public.congestion_obs      enable row level security;
alter table public.congestion_forecast enable row level security;
alter table public.sensor_obs          enable row level security;
alter table public.sensor_profile      enable row level security;
alter table public.edge_exposure       enable row level security;
alter table public.fetch_log           enable row level security;  -- 정책 없음: 앱에서 직접 읽지 못함

create policy "public read" on public.hotspots            for select to anon, authenticated using (true);
create policy "public read" on public.sensors             for select to anon, authenticated using (true);
create policy "public read" on public.places              for select to anon, authenticated using (true);
create policy "public read" on public.road_nodes          for select to anon, authenticated using (true);
create policy "public read" on public.road_edges          for select to anon, authenticated using (true);
create policy "public read" on public.congestion_obs      for select to anon, authenticated using (true);
create policy "public read" on public.congestion_forecast for select to anon, authenticated using (true);
create policy "public read" on public.sensor_obs          for select to anon, authenticated using (true);
create policy "public read" on public.sensor_profile      for select to anon, authenticated using (true);
create policy "public read" on public.edge_exposure       for select to anon, authenticated using (true);

grant select on
  public.hotspots, public.sensors, public.places, public.road_nodes, public.road_edges,
  public.congestion_obs, public.congestion_forecast, public.sensor_obs, public.sensor_profile,
  public.edge_exposure
to anon, authenticated;
